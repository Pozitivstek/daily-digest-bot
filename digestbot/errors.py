"""Ошибки внешних источников. Дайджест ловит их по секциям и не падает целиком."""


class SourceError(Exception):
    """Источник данных не дал нужного ответа."""


class FetchError(SourceError):
    """Сеть, таймаут, не-200 или слишком большой ответ."""


class ParseError(SourceError):
    """Ответ получен, но не похож на ожидаемый формат."""
